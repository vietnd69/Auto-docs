"""Self-improving experience library per domain (goal G6).

Entries follow Harness²'s EXPERIENCE shape (cue / lesson / evidence). The library is
bounded, de-duplicated and ranked by how often a lesson was confirmed or retrieved.
"""

from __future__ import annotations

import json
import re
from dataclasses import asdict, dataclass, field
from pathlib import Path

from harness.textutil import short_hash
from harness.timeutil import now_iso
from harness.workspace import Workspace

_WORD = re.compile(r"[a-z0-9_]{3,}")
DUPLICATE_SIMILARITY = 0.6
GENERAL_DOMAIN = "general"


@dataclass
class Experience:
    id: str
    domain: str
    cue: str
    lesson: str
    evidence: str
    uses: int = 0
    confirmations: int = 1
    created: str = field(default_factory=now_iso)
    updated: str = field(default_factory=now_iso)

    @property
    def weight(self) -> int:
        return self.uses + 2 * self.confirmations


def _words(text: str) -> set[str]:
    return set(_WORD.findall(text.lower()))


def _similarity(a: str, b: str) -> float:
    wa, wb = _words(a), _words(b)
    return len(wa & wb) / len(wa | wb) if wa and wb else 0.0


class Library:
    """One domain's experience entries stored as JSONL."""

    def __init__(self, ws: Workspace, domain: str) -> None:
        self.domain = domain
        self.path: Path = ws.library_dir(domain) / "experience.jsonl"
        self.cap = ws.settings.get_int("memory_cap")
        self.entries: list[Experience] = self._load()

    def _load(self) -> list[Experience]:
        if not self.path.exists():
            return []
        rows = self.path.read_text(encoding="utf-8").splitlines()
        return [Experience(**json.loads(r)) for r in rows if r.strip()]

    def save(self) -> None:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        body = "\n".join(json.dumps(asdict(e), ensure_ascii=False) for e in self.entries)
        self.path.write_text(body + ("\n" if body else ""), encoding="utf-8")

    def add(self, cue: str, lesson: str, evidence: str) -> str:
        """Add or confirm a lesson; returns a status message."""
        if not (cue.strip() and lesson.strip() and evidence.strip()):
            return "rejected: cue, lesson and evidence are all required"
        for entry in self.entries:
            if _similarity(entry.cue, cue) >= DUPLICATE_SIMILARITY:
                entry.confirmations += 1
                entry.updated = now_iso()
                if len(lesson) > len(entry.lesson):
                    entry.lesson, entry.evidence = lesson, evidence
                self.save()
                return f"confirmed existing lesson {entry.id}"
        entry = Experience(short_hash(f"{self.domain}|{cue}", 10), self.domain, cue, lesson, evidence)
        self.entries.append(entry)
        if len(self.entries) > self.cap:
            self.entries.sort(key=lambda e: (e.weight, e.updated), reverse=True)
            del self.entries[self.cap :]
        self.save()
        return f"added lesson {entry.id}"

    def search(self, query: str, k: int = 5) -> list[Experience]:
        scored = [(_similarity(query, f"{e.cue} {e.lesson}") + e.weight / 1000, e) for e in self.entries]
        hits = [e for score, e in sorted(scored, key=lambda x: x[0], reverse=True) if score > 0.001][:k]
        for entry in hits:
            entry.uses += 1
        if hits:
            self.save()
        return hits


def search(ws: Workspace, domain: str, query: str, k: int = 5) -> str:
    hits = Library(ws, domain).search(query, k) + Library(ws, GENERAL_DOMAIN).search(query, 2)
    if not hits:
        return "no lessons yet for this domain"
    return "\n\n".join(f"[{e.id}] WHEN {e.cue}\nDO {e.lesson}\n(evidence: {e.evidence})" for e in hits)


def render_long_term(ws: Workspace, domains: list[str], top_n: int) -> str:
    """Summary of the strongest lessons across domains for ``LongTermMEMORY.md``."""
    entries = [e for d in [*domains, GENERAL_DOMAIN] for e in Library(ws, d).entries]
    entries.sort(key=lambda e: e.weight, reverse=True)
    lines = ["# Long-term memory", "", "Generated by `mod-harness memory --render`; do not edit by hand.", ""]
    lines += [f"- **[{e.domain}] When** {e.cue} — **do** {e.lesson}" for e in entries[:top_n]]
    return "\n".join(lines) + "\n"
