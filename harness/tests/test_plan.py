from __future__ import annotations

from harness.autoplan import auto_plan
from harness.codeindex import FileIndex, build_file_index, index_codebase
from harness.lua_parse import LuaSymbol
from harness.plan import DocPlan, Page, SourceRef, load_plan, save_plan, validate_plan
from harness.workspace import Workspace


def codes(plan: DocPlan, index: dict[str, FileIndex]) -> set[str]:
    return {i.code for i in validate_plan(plan, index)}


def test_auto_plan_is_valid_and_classifies(ws: Workspace) -> None:
    index = index_codebase(ws)
    plan = auto_plan(index, {"build": "1", "sha": "x"}, 12000)
    assert validate_plan(plan, index) == []
    kinds = {p.id: p.kind for p in plan.pages}
    assert kinds["components/health"] == "api"
    assert kinds["strings_small"] == "data"
    assert plan.page("stategraphs/SGpig").category == ["Stategraphs"]


def test_large_file_is_split_with_overview(ws: Workspace) -> None:
    index = index_codebase(ws)
    plan = auto_plan(index, {"build": "1", "sha": "x"}, budget=40)
    ids = [p.id for p in plan.pages if p.id.startswith("stategraphs/SGpig/")]
    assert "stategraphs/SGpig/index" in ids and len(ids) >= 3
    assert plan.page("stategraphs/SGpig/index").kind == "overview"
    assert not [i for i in validate_plan(plan, index) if i.code in ("UNASSIGNED", "DUPLICATE")]


def test_small_data_files_are_merged() -> None:
    files = {
        f"map/rooms/r{i}.lua": build_file_index(
            f"map/rooms/r{i}.lua", f"-- AUTOGENERATED\nT{i} = {{ a = 1 }}\n"
        )
        for i in range(4)
    }
    plan = auto_plan(files, {}, 12000)
    assert [p.id for p in plan.pages] == ["map/rooms/collection-1"]
    assert len(plan.pages[0].sources) == 4
    assert validate_plan(plan, files) == []


def test_validate_plan_reports_each_problem(ws: Workspace) -> None:
    index = index_codebase(ws)
    good = auto_plan(index, {}, 12000)
    dup = Page(
        "dup", "components/health.md", "x", "component", "api", [], [SourceRef("components/health.lua")]
    )
    bad = Page("bad", "../x.txt", "x", "core", "weird", [], [SourceRef("missing.lua", ["Nope"])])
    empty = Page("empty", "empty.md", "x", "core", "api", [], [])
    ghost = Page(
        "ghost", "ghost.md", "x", "core", "api", [], [SourceRef("components/health.lua", ["Health:Nope"])]
    )
    found = codes(DocPlan({}, [*good.pages, dup, bad, empty, ghost]), index)
    assert {
        "DUPLICATE_PAGE",
        "DUPLICATE",
        "BAD_PATH",
        "BAD_KIND",
        "UNKNOWN_FILE",
        "EMPTY_PAGE",
        "UNKNOWN_SYMBOL",
    } <= found
    assert "UNCOVERED_FILE" in codes(DocPlan({}, good.pages[1:]), index)


def test_over_budget_only_for_multi_symbol_pages() -> None:
    sym = [LuaSymbol("method", f"M{i}", f"C:M{i}", i * 10 + 1, i * 10 + 10) for i in range(3)]
    fi = FileIndex("c.lua", "component", 3000, 30, False, sym, [s.qualname for s in sym])
    many = Page("c", "c.md", "C", "component", "api", [], [SourceRef("c.lua")], budget_tokens=100)
    assert "OVER_BUDGET" in codes(DocPlan({}, [many]), {"c.lua": fi})
    one = FileIndex("c.lua", "component", 3000, 30, False, sym[:1], [sym[0].qualname])
    assert "OVER_BUDGET" not in codes(DocPlan({}, [many]), {"c.lua": one})


def test_plan_roundtrip(ws: Workspace) -> None:
    plan = auto_plan(index_codebase(ws), {"build": "1", "sha": "x"}, 12000)
    save_plan(plan, ws.plan_path)
    loaded = load_plan(ws.plan_path)
    assert loaded.to_json() == plan.to_json()
    assert loaded.pages_for_file("components/health.lua")[0].id == "components/health"
